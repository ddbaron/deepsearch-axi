def test_setup_repairs_a_moved_executable(home_dir: Path, project_dir: Path) -> None:
    executable = _fake_console(home_dir)
    environment = _env(home_dir)
    first = _setup(executable, environment, project_dir)
    assert first.code == 0, (first.stdout, first.stderr)

    moved = home_dir / "relocated" / "deepsearch-axi"
    moved.parent.mkdir()
    shutil.move(str(executable), moved)
    moved_environment = _env(home_dir)

    repaired = _setup(moved, moved_environment, project_dir)
    assert repaired.code == 0, (repaired.stdout, repaired.stderr)
    assert repaired.stderr == ""
    document = decode(repaired.stdout)
    assert {row["status"] for row in document["hosts"]} == {"repaired"}

    old = str(executable)
    for relative in (CLAUDE, CODEX_HOOKS):
        text = (project_dir / relative).read_text(encoding="utf-8")
        assert old not in text, relative
        assert str(moved) in text, relative
    plugin = (project_dir / PLUGIN).read_text(encoding="utf-8")
    assert old not in plugin
    assert json.dumps(str(moved)) in plugin
    manifest = json.loads((project_dir / MANIFEST).read_text(encoding="utf-8"))
    assert manifest["executable"] == str(moved)
    assert manifest["command"] == [str(moved)]

    hooks = json.loads((project_dir / CLAUDE).read_text(encoding="utf-8"))
    command = _owned_commands(hooks, "SessionStart")[0]
    assert command.startswith(str(moved))
    completed = _run_hook(
        command,
        project_dir,
        moved_environment,
        _native_payload("relocated-session", project_dir, "SessionStart"),
    )
    assert completed.returncode == 0, completed.stderr
    assert decode(completed.stdout.decode("utf-8"))["integration"] == "installed"

    assert _home(moved, moved_environment, project_dir)["integrations"] == {
        "claude-code": "installed",
        "codex": "installed",
        "opencode": "installed",
    }
    stable = _snapshot(project_dir)
    again = _setup(moved, moved_environment, project_dir)
    assert again.code == 0 and again.stdout == "" and again.stderr == ""
    assert _snapshot(project_dir) == stable


