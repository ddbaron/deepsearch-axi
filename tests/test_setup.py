"""Behavioral setup tests for the three native project integrations.

Every test drives the real console-script child process with an isolated HOME,
a temporary project and a fake key.  Generated Claude Code and Codex hooks are
executed as subprocesses with native lifecycle JSON, and the OpenCode plugin is
generated by the same setup run (its Node execution lives in test_opencode.py).
"""

from __future__ import annotations

import copy
import json
import os
import shlex
import shutil
import subprocess
import sys
from collections.abc import Mapping
from pathlib import Path

import pytest
from support.cli import decode, run_cli
from support.env import FAKE_KEY, isolated_env

MANIFEST = Path(".deepsearch-axi") / "manifest.json"
CLAUDE = Path(".claude") / "settings.json"
CODEX_HOOKS = Path(".codex") / "hooks.json"
CODEX_CONFIG = Path(".codex") / "config.toml"
PLUGIN = Path(".opencode") / "plugins" / "deepsearch-axi.js"


def _fake_console(home: Path) -> Path:
    script = home / "bin" / "deepsearch-axi"
    script.parent.mkdir(parents=True)
    script.write_text(
        f"#!{sys.executable}\nfrom deepsearch_axi._entry import main\nraise SystemExit(main())\n",
        encoding="utf-8",
    )
    script.chmod(0o755)
    return script


def _env(home: Path, **overrides: str) -> dict[str, str]:
    # Keep the fake console off PATH so setup records its absolute path.
    environment = isolated_env(home, DEEPSEEK_API_KEY=FAKE_KEY, **overrides)
    environment["PATH"] = os.environ.get("PATH", "")
    return environment


def _setup(
    executable: Path,
    environment: Mapping[str, str],
    project: Path,
    *arguments: str,
):
    return run_cli(
        ["setup", *arguments],
        env=environment,
        cwd=project,
        executable=[str(executable)],
    )


def _snapshot(root: Path) -> dict[str, tuple[bytes, int]]:
    snapshot: dict[str, tuple[bytes, int]] = {}
    for path in sorted(root.rglob("*")):
        if path.is_file() and not path.is_symlink():
            snapshot[str(path.relative_to(root))] = (
                path.read_bytes(),
                path.stat().st_mtime_ns,
            )
    return snapshot


def _owned_commands(document: dict, event: str) -> list[str]:
    commands: list[str] = []
    for group in document["hooks"][event]:
        for handler in group.get("hooks", []):
            command = handler.get("command")
            if isinstance(command, str) and "deepsearch-axi session" in command:
                commands.append(command)
    return commands


def _expected_command(executable: Path, agent: str, event: str, project: Path) -> str:
    return shlex.join(
        [
            str(executable),
            "session",
            event,
            "--agent",
            agent,
            "--project",
            str(project.resolve()),
        ]
    )


def _run_hook(command: str, project: Path, environment: Mapping[str, str], payload: dict):
    return subprocess.run(
        shlex.split(command),
        cwd=str(project),
        env=dict(environment),
        input=json.dumps(payload).encode("utf-8"),
        capture_output=True,
        timeout=60,
    )


def _native_payload(session_id: str, project: Path, event: str) -> dict:
    payload = {
        "session_id": session_id,
        "transcript_path": "/never/read.jsonl",
        "cwd": str(project.resolve()),
        "hook_event_name": event,
    }
    payload["source" if event == "SessionStart" else "reason"] = "startup"
    return payload


def _home(executable: Path, environment: Mapping[str, str], project: Path):
    run = run_cli([], env=environment, cwd=project, executable=[str(executable)])
    assert run.code == 0, (run.stdout, run.stderr)
    assert run.stderr == ""
    return decode(run.stdout)


def _damage_start_handler(config_path: Path, damage: str) -> None:
    """Rewrite the owned SessionStart handler with one non-canonical field change."""
    document = json.loads(config_path.read_text(encoding="utf-8"))
    handler = document["hooks"]["SessionStart"][0]["hooks"][0]
    if damage == "extra-timeout":
        handler["timeout"] = 5
    elif damage == "missing-type":
        del handler["type"]
    else:
        raise AssertionError(f"unknown damage mode: {damage}")
    config_path.write_text(json.dumps(document), encoding="utf-8")


def test_setup_installs_three_native_hosts_and_context(home_dir: Path, project_dir: Path) -> None:
    executable = _fake_console(home_dir)
    environment = _env(home_dir)

    # Pre-existing unrelated configuration must survive a repair.
    claude_document = {
        "model": "opus",
        "hooks": {
            "SessionStart": [
                {
                    "matcher": "startup",
                    "hooks": [{"type": "command", "command": "echo unrelated"}],
                },
                {
                    "hooks": [
                        {
                            "type": "command",
                            "command": shlex.join(
                                [
                                    "/opt/old/deepsearch-axi",
                                    "session",
                                    "start",
                                    "--agent",
                                    "claude-code",
                                    "--project",
                                    str(project_dir.resolve()),
                                ]
                            ),
                        }
                    ]
                },
            ]
        },
    }
    (project_dir / ".claude").mkdir()
    (project_dir / CLAUDE).write_text(
        json.dumps(claude_document, indent=2) + "\n", encoding="utf-8"
    )
    (project_dir / ".codex").mkdir()
    (project_dir / CODEX_CONFIG).write_text(
        '# keep this comment\nmodel = "gpt-5"\n\n[features]\nhooks = false\n',
        encoding="utf-8",
    )

    run = _setup(executable, environment, project_dir)
    assert run.code == 0, (run.stdout, run.stderr)
    assert run.stderr == ""
    document = decode(run.stdout)
    assert document["setup"] == {"project": str(project_dir.resolve()), "changed": True}
    assert [(row["agent"], row["status"]) for row in document["hosts"]] == [
        ("claude-code", "installed"),
        ("codex", "installed"),
        ("opencode", "installed"),
    ]

    claude = json.loads((project_dir / CLAUDE).read_text(encoding="utf-8"))
    assert claude["model"] == "opus"
    assert claude["hooks"]["SessionStart"][0] == claude_document["hooks"]["SessionStart"][0]
    assert _owned_commands(claude, "SessionStart") == [
        _expected_command(executable, "claude-code", "start", project_dir)
    ]
    assert _owned_commands(claude, "SessionEnd") == [
        _expected_command(executable, "claude-code", "end", project_dir)
    ]

    codex = json.loads((project_dir / CODEX_HOOKS).read_text(encoding="utf-8"))
    assert _owned_commands(codex, "SessionStart") == [
        _expected_command(executable, "codex", "start", project_dir)
    ]
    assert _owned_commands(codex, "SessionEnd") == [
        _expected_command(executable, "codex", "end", project_dir)
    ]
    config = (project_dir / CODEX_CONFIG).read_text(encoding="utf-8")
    assert "# keep this comment" in config
    assert 'model = "gpt-5"' in config
    assert "hooks = true" in config
    assert "hooks = false" not in config

    plugin = (project_dir / PLUGIN).read_text(encoding="utf-8")
    assert plugin.startswith("// managed-by: deepsearch-axi\n")
    assert json.dumps(str(executable)) in plugin
    assert json.dumps(str(project_dir.resolve())) in plugin

    manifest = json.loads((project_dir / MANIFEST).read_text(encoding="utf-8"))
    assert manifest["executable"] == str(executable)
    assert manifest["command"] == [str(executable)]
    assert sorted(manifest["hosts"]) == ["claude-code", "codex", "opencode"]
    assert (project_dir / ".deepsearch-axi" / ".gitignore").read_text(encoding="utf-8") == "*\n"

    home_view = _home(executable, environment, project_dir)
    assert home_view["integrations"] == {
        "claude-code": "installed",
        "codex": "installed",
        "opencode": "installed",
    }

    # Execute both generated native start and end hooks for both hosts.
    for agent, path, event_names in (
        ("claude-code", CLAUDE, ("SessionStart", "SessionEnd")),
        ("codex", CODEX_HOOKS, ("SessionStart", "SessionEnd")),
    ):
        hooks = json.loads((project_dir / path).read_text(encoding="utf-8"))
        for event in event_names:
            command = _owned_commands(hooks, event)[0]
            completed = _run_hook(
                command,
                project_dir,
                environment,
                _native_payload(f"{agent}-{event}", project_dir, event),
            )
            assert completed.returncode == 0, (agent, event, completed.stderr)
            assert completed.stderr == b""
            decoded = decode(completed.stdout.decode("utf-8"))
            if event == "SessionStart":
                assert decoded["cwd"] == str(project_dir.resolve())
                assert decoded["integration"] == "installed"
                assert decoded["auth"] == {"state": "configured"}
                assert FAKE_KEY not in completed.stdout.decode("utf-8")
            else:
                assert decoded == {"session": {"event": "end", "recorded": True}}

    state = json.loads((project_dir / ".deepsearch-axi" / "state.json").read_text(encoding="utf-8"))
    assert {record["agent"] for record in state["sessions"]} == {"claude-code", "codex"}
    assert {record["scope"] for record in state["sessions"]} == {"."}
    stored = json.dumps(state)
    assert "claude-code-SessionStart" not in stored
    assert "codex-SessionEnd" not in stored
    assert "transcript" not in stored


